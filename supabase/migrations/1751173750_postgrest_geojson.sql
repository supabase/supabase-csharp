create extension if not exists postgis schema extensions;

create table public.places
(
    id       bigint generated by default as identity primary key,
    name     text not null,
    location extensions.geometry(Point, 4326)
);

grant select, insert, update, delete on table public.places to anon, authenticated, service_role;
grant usage, select on sequence public.places_id_seq to anon, authenticated, service_role;
